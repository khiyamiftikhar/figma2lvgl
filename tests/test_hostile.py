"""The hostile naming fixture (tests/fixtures/hostile/).

Layer names built to break naming (design doc 10, section 8), generated by
the real CLI. Every name in the output is checked against C1 and C5, plus
the specific results doc 10 promises. The same design is a compile case (C
and C++) and a full-output golden case. The two error fixtures must stop
the CLI with a message naming the layers.
"""

import re
import subprocess
import sys
from pathlib import Path

import pytest

from figma2lvgl.core import naming

ROOT = Path(__file__).resolve().parents[1]
HOSTILE = ROOT / "tests" / "fixtures" / "hostile"


def run_cli(xml, out):
    return subprocess.run(
        [sys.executable, "-m", "figma2lvgl.main", "-x", str(xml), "-i", str(HOSTILE),
         "-d", str(out), "-y"],
        cwd=ROOT, capture_output=True, text=True)


@pytest.fixture(scope="module")
def generated(tmp_path_factory):
    out = tmp_path_factory.mktemp("hostile")
    result = run_cli(HOSTILE / "hostile.xml", out)
    assert result.returncode == 0, result.stdout + result.stderr
    ui = out / "ui_src"
    return {
        "log": result.stdout + result.stderr,
        "files": sorted(p.relative_to(ui).as_posix() for p in ui.rglob("*") if p.is_file()),
        "h": (ui / "include" / "ui_hostile.h").read_text(encoding="utf-8"),
        "c": (ui / "src" / "ui_hostile.c").read_text(encoding="utf-8"),
        "all_c": "\n".join(p.read_text(encoding="utf-8") for p in (ui / "src").glob("*.c")),
        "all_h": "\n".join(p.read_text(encoding="utf-8") for p in (ui / "include").glob("*.h")),
    }


def functions(header):
    return re.findall(r"\b(ui_\w+)\(", header)


def members(c_text):
    return re.findall(r"^\s*\}\s*(\w+);", c_text, re.M)


def test_every_name_valid_c_and_cpp(generated):  # C1, C5
    names = set(functions(generated["all_h"])) | set(members(generated["all_c"]))
    assert names
    bad = sorted(n for n in names if not naming.is_valid_identifier(n))
    assert bad == []
    assert not [n for n in names if n.startswith("lv_")]


def test_external_symbols_unique(generated):  # C3
    protos = functions(generated["all_h"])
    assert len(protos) == len(set(protos))


@pytest.mark.parametrize("member", [
    "label_2nd_row", "label_default", "label_class", "label_1", "label_2",
    "label_style", "label_lv_obj",
    "title", "title_3", "title_2", "title_4",     # natural title_2 kept
    "icon_wifi", "icon_wifi_2",
])
def test_top_level_members(generated, member):  # N3, N12, N15
    assert member in members(generated["c"])


def test_same_name_in_different_panels_kept(generated):  # N1
    c = generated["c"]
    # panel_a holds its own 'title' and 'btn_ok'; panel_b its own 'btn_ok'
    assert "s_hostile.panel_a.title" in c and "s_hostile.panel_a.btn_ok" in c
    assert "s_hostile.panel_b.btn_ok" in c
    assert "s_hostile.panel_a.label_text" in c        # 'text' inside a panel


@pytest.mark.parametrize("fn", [
    "ui_hostile_on_panel_a_btn_ok_clicked",          # qualified, one level
    "ui_hostile_on_panel_b_btn_ok_clicked",
    "ui_hostile_on_x_panel_c_btn_go_clicked",        # qualified, two levels
    "ui_hostile_on_y_panel_c_btn_go_clicked",
    "ui_hostile_a_b_c_deep_set_text",                # full path (N4)
    "ui_hostile_panel_d_e_label_set_text",           # flattened alike ...
    "ui_hostile_panel_d_e_label_set_text_2",         # ... second gets _2
    "ui_hostile_label_default_set_text",             # no "__"
])
def test_functions(generated, fn):
    assert fn in functions(generated["h"])


def test_screens_with_reserved_names(generated):  # N17
    files = generated["files"]
    assert "src/ui_style_3.c" in files and "include/ui_style_3.h" in files
    assert "src/ui_style_2.c" in files                 # natural style_2 kept
    assert files.count("priv_src/ui_style.c") == 1     # the bundled file
    assert "UI_STYLE_3_H" in generated["all_h"]


def test_image_names(generated):  # N13, N17
    c = generated["c"]
    assert "s_hostile.ui_style.src = &image_ui_style;" in c
    assert "s_hostile.icon_wifi.src = &icon_wifi;" in c
    assert "s_hostile.icon_wifi_2.src = &icon_wifi;" in c   # shared picture
    assert "priv_src/icon_wifi_2.c" not in generated["files"]


@pytest.mark.parametrize("text", [
    "frame 'style': screen name 'style' would write ui_style.c/.h",
    "layer '2nd row': name '2nd_row' is not usable in C",
    "layer 'style': 'style' is a generated field name; using 'label_style'",
    "'title' is already used by 'title'; using 'title_3'",
    "layers icon_wifi, icon_wifi all show icon_wifi.png",
    "layer 'label': 'ui_hostile_panel_d_e_label_set_text' is already used by 'e_label'",
    "image file 'ui_style.c' would replace a figma2lvgl file; using 'image_ui_style'",
])
def test_every_rename_reported(generated, text):  # C8
    assert text in generated["log"]


@pytest.mark.parametrize("xml, layers", [
    ("screen_collision.xml", ["frames 'Home' and 'home'", "screen name 'home'"]),
    ("asset_conflict.xml", ["icon_wifi, icon_wifi", "different components"]),
])
def test_error_fixtures(tmp_path, xml, layers):
    result = run_cli(HOSTILE / xml, tmp_path)
    log = result.stdout + result.stderr
    assert result.returncode == 1
    assert "Traceback" not in log
    for text in layers:
        assert text in log
    assert not (tmp_path / "ui_src").exists()


def test_png_with_reserved_stem_rejected(tmp_path):
    images = tmp_path / "images"
    images.mkdir()
    (images / "ui_style.png").write_bytes((HOSTILE / "icon_wifi.png").read_bytes())
    xml = tmp_path / "d.xml"
    xml.write_text('<page name="p"><children><Frame name="home" width="320" height="480">'
                   '<children/></Frame></children></page>', encoding="utf-8")
    result = subprocess.run(
        [sys.executable, "-m", "figma2lvgl.main", "-x", str(xml), "-i", str(images),
         "-d", str(tmp_path / "out"), "-y"], cwd=ROOT, capture_output=True, text=True)
    assert result.returncode == 1
    assert "image file ui_style.png would replace figma2lvgl's own ui_style.c" in result.stdout + result.stderr
